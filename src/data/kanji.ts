// Stable per-kanji slug used for its image and audio files
// (e.g. 休 -> "rest" -> mnemonics/kanji-rest.png, audio/kanji-read-rest.mp3).
export function kanjiId(k: KanjiChar): string {
  const m = k.mnemonicImage?.match(/kanji-([a-z]+)\.png/);
  return m ? m[1] : k.romaji;
}

